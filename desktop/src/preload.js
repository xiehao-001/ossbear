const { contextBridge, ipcRenderer } = require("electron");

const call = (name, args) => ipcRenderer.invoke("sb:call", name, args || {});

contextBridge.exposeInMainWorld("sb", {
  status: () => call("status"),
  login: (a) => call("login", a),
  register: (a) => call("register", a),
  registerCode: (a) => call("registerCode", a),
  logout: () => call("logout"),
  getConfig: () => call("getConfig"),
  saveConfig: (a) => call("saveConfig", a),
  browse: (path) => call("browse", { path }),
  apps: () => call("apps"),
  providers: () => call("listProviders"),
  saveProvider: (a) => call("saveProvider", a),
  updateProvider: (a) => call("updateProvider", a),
  deleteProvider: (id, force) => call("deleteProvider", { id, force }),
  testProvider: (a) => call("testProvider", a),
  providerBalance: (id) => call("providerBalance", { id }),
  stitches: () => call("listStitches"),
  saveStitch: (a) => call("saveStitch", a),
  deleteStitch: (id) => call("deleteStitch", { id }),
  files: (a) => call("files", a),
  scan: (a) => call("scan", a),
  jobs: () => call("jobs"),
  job: (id) => call("job", { id }),
  archive: (a) => call("archive", a),
  restore: (a) => call("restore", a),
  share: (a) => call("share", a),
  downloads: () => call("downloads"),
  link: (path) => call("link", { path }),
  preview: (path) => ipcRenderer.invoke("sb:preview-open", path),
  open: (path) => call("open", { path }),
  fetch: (path) => call("fetch", { path }),
  reveal: (path) => call("reveal", { path }),
  logs: (a) => call("logs", a || {}),
  log: (id) => call("log", { id }),
  devices: () => call("devices"),
  summary: () => call("summary"),
  syncMeta: () => call("syncMeta"),
  drive: () => call("drive"),
  driveAction: (action) => call("driveAction", { action }),
  repairDrive: () => call("driveRepair"),
  driveConfig: (a) => call("driveConfig", a),
  appInfo: () => ipcRenderer.invoke("sb:app-info"),
  checkUpdate: () => ipcRenderer.invoke("sb:check-update"),
  chooseDirs: () => ipcRenderer.invoke("sb:choose-dirs"),
  chooseFiles: () => ipcRenderer.invoke("sb:choose-files"),
  openExternal: (url) => ipcRenderer.invoke("sb:open-external", url),
  copy: (text) => ipcRenderer.invoke("sb:copy", text),
  openFolder: (kind) => ipcRenderer.invoke("sb:open-folder", kind),
  setAutoStart: (on) => ipcRenderer.invoke("sb:auto-start", on),
  quickMenu: (on) => ipcRenderer.invoke("sb:set-quick-menu", on),
  onBackendExit: (fn) => ipcRenderer.on("sb:backend-exit", (e, code) => fn(code)),
  onFilesChanged: (fn) => ipcRenderer.on("sb:files-changed", () => fn()),
});
